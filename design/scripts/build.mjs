// Compiles design/system/tokens.json into design/tokens.css (everything the app needs) and
// design/site-fonts.css (the faces only the landing page uses).
//   node design/scripts/build.mjs          write the files
//   node design/scripts/build.mjs --check  fail if the committed files are out of date
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const DESIGN = join(dirname(fileURLToPath(import.meta.url)), '..');
export const TOKENS_PATH = join(DESIGN, 'system/tokens.json');
export const CSS_PATH = join(DESIGN, 'tokens.css');
export const SITE_FONTS_PATH = join(DESIGN, 'site-fonts.css');
/** Text styles in this group belong to the landing page; a font only they use stays out of the app. */
const SITE_GROUP = 'Site';

export function readTokens() {
  return JSON.parse(readFileSync(TOKENS_PATH, 'utf8'));
}

/** Token families that hold a flat list of `{name, value, usage}` entries (everything but `type`). */
export function listFamilies(tokens) {
  return Object.entries(tokens).filter(([key, family]) => key !== 'type' && Array.isArray(family?.tokens));
}

/** The `font` shorthand of a text style, as bundle.css writes its `--type-*` variables. */
export function typeShorthand(style, group) {
  const italic = style.fontStyle === 'italic' ? 'italic ' : '';
  return `${italic}${style.fontWeight} ${style.fontSize}/${style.lineHeight} var(--font-${style.family ?? group.family})`;
}

/** `{other-token}` → `other-token`; anything else → undefined. */
export function aliasOf(value) {
  return /^\{(.+)\}$/.exec(value)?.[1];
}

const cssValue = (value) => (aliasOf(value) ? `var(--${aliasOf(value)})` : value);

const fontFace = (font, fontBase) =>
  `@font-face {\n  font-family: "${font.family}";\n  src: url("${fontBase}${font.file}") format("woff2");\n  font-weight: ${font.weight};\n  font-style: ${font.style};\n  font-display: swap;\n}`;

/** True when every text style set in this font belongs to the landing page. */
function isSiteOnly(font, tokens) {
  const stacks = Object.entries(tokens.type.families)
    .filter(([, stack]) => stack.split(',')[0].trim().replace(/"/g, '') === font.family)
    .map(([key]) => key);
  const groups = tokens.type.groups.filter((group) => group.styles.some((style) => stacks.includes(style.family ?? group.family)));
  return groups.length > 0 && groups.every((group) => group.name === SITE_GROUP);
}

/** The @font-face rules of the landing-page-only fonts. */
export function compileSiteFonts(tokens, fontBase = 'system/') {
  const faces = tokens.type.fonts.filter((font) => isSiteOnly(font, tokens)).map((font) => fontFace(font, fontBase));
  return ['/* Practice Piano: fonts only the landing page uses. Generated by `npm run design:build`. Do not edit. */', '', ...faces, ''].join('\n');
}

/** `fontBase` is the path from the stylesheet to design/system/. */
export function compile(tokens, fontBase = 'system/') {
  const themes = tokens.color.themes.map((t) => t.id);
  const valueIn = (token, theme) => (typeof token.value === 'string' ? token.value : (token.value[theme] ?? token.value[themes[0]]));
  const themed = [...tokens.color.tokens, ...(tokens.shadow?.tokens ?? [])];
  const plain = listFamilies(tokens)
    .filter(([key]) => key !== 'color' && key !== 'shadow')
    .flatMap(([, family]) => family.tokens);
  const lines = (entries) => entries.map(([name, value]) => `  --${name}: ${value};`).join('\n');

  const out = ['/* Practice Piano tokens. Generated from design/system/tokens.json by `npm run design:build`. Do not edit. */', ''];

  for (const font of tokens.type.fonts) {
    if (!isSiteOnly(font, tokens)) out.push(fontFace(font, fontBase));
  }

  out.push(
    '',
    `/* Colors and shadows: ${themes[0]} theme (the default). */`,
    `:root,\n[data-theme="${themes[0]}"] {\n  color-scheme: ${themes[0]};\n${lines(themed.map((t) => [t.name, cssValue(valueIn(t, themes[0]))]))}\n}`,
  );
  for (const theme of themes.slice(1)) {
    const changed = themed.filter((t) => typeof t.value !== 'string');
    out.push(
      '',
      `/* ${theme} theme: only what differs. */`,
      `[data-theme="${theme}"] {\n  color-scheme: ${theme};\n${lines(changed.map((t) => [t.name, cssValue(valueIn(t, theme))]))}\n}`,
    );
  }

  const type = [];
  for (const group of tokens.type.groups) {
    for (const style of group.styles) {
      type.push([`type-${style.name}`, typeShorthand(style, group)]);
      if (style.letterSpacing) type.push([`tracking-${style.name}`, style.letterSpacing]);
    }
  }
  out.push(
    '',
    '/* Scales, font stacks and text styles (set a text style with `font: var(--type-body)`). */',
    `:root {\n${lines(plain.map((t) => [t.name, t.value]))}\n${lines(Object.entries(tokens.type.families).map(([key, stack]) => [`font-${key}`, stack]))}\n${lines(type)}\n}`,
    '',
  );
  return out.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const tokens = readTokens();
  const files = [
    [CSS_PATH, compile(tokens)],
    [SITE_FONTS_PATH, compileSiteFonts(tokens)],
  ];
  if (process.argv.includes('--check')) {
    const stale = files.filter(([path, css]) => {
      try {
        return readFileSync(path, 'utf8') !== css;
      } catch {
        return true; // a missing file counts as out of date
      }
    });
    if (stale.length) {
      console.error('The generated stylesheets in design/ are out of date. Run `npm run design:build` and commit the result.');
      process.exit(1);
    }
  } else {
    mkdirSync(DESIGN, { recursive: true });
    for (const [path, css] of files) {
      writeFileSync(path, css);
      console.log(`Wrote design/${basename(path)} (${css.length} bytes)`);
    }
  }
}
